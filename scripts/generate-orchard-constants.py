#!/usr/bin/env python3
"""Generate Lean constants from the hash-pinned organizer JSON; --check detects drift."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "fixtures/hashsmash/orchard"
OUTPUT = ROOT / "lean/ZkGadgets/Poseidon/Constants.lean"
MODULUS = 0x40000000000000000000000000000000224698fc094cf91b992d30ed00000001


def render():
    manifest = json.loads((FIXTURE / "manifest.json").read_text())
    for name, expected in manifest["files"].items():
        data = (FIXTURE / "upstream" / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(f"pinned input changed: {name}")
    data = json.loads((FIXTURE / "upstream/pareto/orchard-pallas-constants.json").read_text())
    rows = []
    for key, count in [("round_constants", 64), ("mds", 3)]:
        matrix = data[key]
        if len(matrix) != count or any(len(row) != 3 for row in matrix):
            raise ValueError(f"invalid {key} dimensions")
        parsed = [[int(x, 16) for x in row] for row in matrix]
        if any(not 0 <= x < MODULUS for row in parsed for x in row):
            raise ValueError(f"noncanonical {key}")
        rows.append(parsed)
    lines = [
        "-- Generated by scripts/generate-orchard-constants.py; do not edit.",
        "-- Organizer source revision: " + manifest["organizer_revision"],
        "-- JSON SHA-256: " + manifest["files"]["pareto/orchard-pallas-constants.json"],
        "namespace Scribe.Poseidon.Orchard",
        f"def modulus : Nat := {MODULUS}",
    ]
    for name, matrix in zip(["roundConstants", "mds"], rows):
        lines.append(f"def {name} : Array (Nat × Nat × Nat) := #[")
        lines.append(",\n".join("  (" + ", ".join(map(str, row)) + ")" for row in matrix))
        lines.append("]")
    lines.append("end Scribe.Poseidon.Orchard")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit("generated Lean constants differ from pinned JSON")
        print("Pinned inputs and Lean constants match")
    else:
        OUTPUT.write_text(expected)
